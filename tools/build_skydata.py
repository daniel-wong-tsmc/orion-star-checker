"""Build js/skydata.js from the d3-celestial data folder.

Usage: python3 tools/build_skydata.py <path to d3-celestial/data>
Get the data with: npm pack d3-celestial && tar xzf d3-celestial-*.tgz
"""
import json
import math
import sys

D = sys.argv[1].rstrip('/') + '/'
OUT = 'js/skydata.js'


def load(f):
    with open(D + f) as fh:
        return json.load(fh)


def ra(x):
    return round(x % 360, 3)


# Stars to magnitude 6, flattened as [ra_deg, dec, mag, bv, ...].
names = load('starnames.json')
flat, named = [], []
for s in load('stars.6.json')['features']:
    lon, lat = s['geometry']['coordinates']
    m = s['properties']['mag']
    try:
        bv = float(s['properties']['bv'])
    except (TypeError, ValueError):
        bv = 0.6
    flat += [ra(lon), round(lat, 3), round(m, 2), round(bv, 2)]
    n = names.get(str(s['id']))
    if n and n['name'] and m < 3.6:
        named.append([n['name'], ra(lon), round(lat, 3), round(m, 2), n['c']])

# Constellation stick figures and label positions.
cmeta = {f['id']: f for f in load('constellations.json')['features']}
cons = []
for f in load('constellations.lines.json')['features']:
    p = cmeta[f['id']]['properties']
    g = cmeta[f['id']]['geometry']['coordinates']
    lines = [[v for pt in ln for v in (ra(pt[0]), round(pt[1], 3))] for ln in f['geometry']['coordinates']]
    cons.append({'id': f['id'], 'name': p['name'], 'en': p['en'], 'rank': int(p['rank']),
                 'ra': ra(g[0]), 'dec': g[1], 'lines': lines})

# Messier objects.
dso = []
for f in load('messier.json')['features']:
    p = f['properties']
    lon, lat = f['geometry']['coordinates']
    mag = p['mag'] if isinstance(p['mag'], (int, float)) else 9
    dso.append([p['name'], p.get('alt') or '', p['type'], ra(lon), lat, mag])


# Milky Way: sample a grid and record how many brightness outlines hold each point.
def inside_ring(x, y, ring):
    pts, prev = [], None
    for lon, lat in ring:
        if prev is not None:
            while lon - prev > 180:
                lon -= 360
            while lon - prev < -180:
                lon += 360
        pts.append((lon, lat))
        prev = lon
    hit = False
    for xx in (x - 720, x - 360, x, x + 360, x + 720):
        c, j = False, len(pts) - 1
        for i in range(len(pts)):
            xi, yi = pts[i]
            xj, yj = pts[j]
            if (yi > y) != (yj > y) and xx < (xj - xi) * (y - yi) / (yj - yi) + xi:
                c = not c
            j = i
        hit = hit or c
    return hit


def inside_poly(x, y, poly):
    return inside_ring(x, y, poly[0]) and not any(inside_ring(x, y, h) for h in poly[1:])


polys = {f['id']: f['geometry']['coordinates'] for f in load('milkyway.json')['features']}
grid, step, dec = [], 1.6, -89.2
while dec < 90:
    n = max(1, int(360 * math.cos(math.radians(dec)) / step))
    for k in range(n):
        lon = -180 + 360 * k / n
        lvl = sum(1 for i in range(1, 6) if inside_poly(lon, dec, polys['ol%d' % i]))
        if lvl:
            grid += [ra(lon), round(dec, 1), lvl]
    dec += step

out = '// Generated by tools/build_skydata.py from d3-celestial (c) 2015 Olaf Frohn, BSD 3-Clause license.\n'
for key, val in (('STARS6', flat), ('NAMED', named), ('CONS', cons), ('DSO', dso), ('MILKY', grid)):
    out += 'export const %s = %s;\n' % (key, json.dumps(val, separators=(',', ':')))
with open(OUT, 'w') as fh:
    fh.write(out)
print(len(flat) // 4, 'stars,', len(named), 'named,', len(cons), 'constellations,',
      len(dso), 'Messier,', len(grid) // 3, 'Milky Way points,', len(out) // 1024, 'KB')
